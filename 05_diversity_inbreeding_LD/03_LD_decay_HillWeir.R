#!/usr/bin/env Rscript

# =============================================================================
# Genome-wide LD decay fitting
#
# R version: 4.5.1
#
# LD decay is modelled according to the Hill and Weir expectation for r²,
# following the R implementation described by Fabio Marroni:
#
# https://fabiomarroni.wordpress.com/2011/08/09/
# estimate-decay-of-linkage-disequilibrium-with-distance/
#
# COMPUTATIONAL ADAPTATION
#
# To efficiently process the large number of pairwise LD observations
# generated genome-wide, r² observations are aggregated according to their
# EXACT physical distance (bp).
#
# For each exact physical distance:
#   - the mean r² is calculated;
#   - the number of SNP pairs contributing to that distance is retained.
#
# The number of SNP pairs is subsequently used as a weight in the nonlinear
# least-squares fit.
#
# No distance binning is introduced: observations are grouped only when they
# have exactly the same physical distance.
#
# Weighting exact-distance means by the corresponding number of SNP pairs
# preserves the least-squares criterion of the original pairwise fitting
# while substantially reducing memory requirements.
#
# Following Marroni's implementation, the LD half-decay distance is estimated
# from the fitted r² values (fpoints). The maximum ESTIMATED LD is used:
#
#   maxld = max(fpoints)
#   h.decay = maxld / 2
#
# and the half-decay distance is defined as the observed physical distance
# whose fitted r² is closest to h.decay.
#
# One genome-wide Hill-Weir fit is performed independently for:
#   PW = P. webbii
#   PD = P. dulcis
#
# =============================================================================


# =============================================================================
# PACKAGES
# =============================================================================

suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
})


# =============================================================================
# SETTINGS
# =============================================================================

# Reference prefix used in 02_LD_dataset_and_calculation.sh.
#
# Examples:
#   REF_PREFIX=DP9H2 Rscript 03_LD_decay_HillWeir.R
#   REF_PREFIX=TUH1  Rscript 03_LD_decay_HillWeir.R

REF_PREFIX <- Sys.getenv(
  "REF_PREFIX",
  unset = "DP9H2"
)


# Directories generated by 02_LD_dataset_and_calculation.sh

INPUT_DIR <- "LD_decay_inputs"
LD_DIR    <- "LD_decay_PLINK"

OUTPUT_DIR <- file.path(
  "LD_decay_results",
  REF_PREFIX
)

dir.create(
  OUTPUT_DIR,
  recursive = TRUE,
  showWarnings = FALSE
)


# Maximum physical distance considered in the PLINK analysis

MAX_DISTANCE_BP <- 500000L


# Number of lines read from the PLINK .ld.gz file at each iteration.
# This can be increased or decreased depending on available RAM.

CHUNK_LINES <- 250000L


# =============================================================================
# POPULATION INPUTS
# =============================================================================

POPULATIONS <- list(

  PW = list(

    species = "P. webbii",

    ld_file = file.path(
      LD_DIR,
      paste0(
        REF_PREFIX,
        "_LDecay_PW_500Kb_AllSNP.ld.gz"
      )
    ),

    fam_file = file.path(
      INPUT_DIR,
      paste0(
        REF_PREFIX,
        "_PW_MAF01.fam"
      )
    )
  ),


  PD = list(

    species = "P. dulcis",

    ld_file = file.path(
      LD_DIR,
      paste0(
        REF_PREFIX,
        "_LDecay_PD_500Kb_AllSNP.ld.gz"
      )
    ),

    fam_file = file.path(
      INPUT_DIR,
      paste0(
        REF_PREFIX,
        "_PD_MAF01.fam"
      )
    )
  )
)


# =============================================================================
# CHECK INPUT FILES
# =============================================================================

for (pop in names(POPULATIONS)) {

  ld_file  <- POPULATIONS[[pop]]$ld_file
  fam_file <- POPULATIONS[[pop]]$fam_file

  if (!file.exists(ld_file)) {
    stop(
      "Missing PLINK LD file for ",
      pop,
      ": ",
      ld_file
    )
  }

  if (!file.exists(fam_file)) {
    stop(
      "Missing PLINK FAM file for ",
      pop,
      ": ",
      fam_file
    )
  }
}


# =============================================================================
# HILL AND WEIR EXPECTATION
# =============================================================================
#
# n = number of sampled alleles
#
# For diploid samples:
#
#   n = 2 * number of individuals
#
# =============================================================================

HW_function <- function(distance, C, n) {

  ((10 + C * distance) /
     ((2 + C * distance) *
        (11 + C * distance))) *

    (1 +

       ((3 + C * distance) *
          (12 +
             12 * C * distance +
             (C * distance)^2)) /

       (n *
          (2 + C * distance) *
          (11 + C * distance))
    )
}


# =============================================================================
# SAMPLE SIZE FROM PLINK FAM
# =============================================================================

get_sample_size <- function(fam_file) {

  fam <- fread(
    fam_file,
    header = FALSE,
    showProgress = FALSE
  )

  if (ncol(fam) < 6L) {
    stop(
      "Invalid PLINK FAM file: ",
      fam_file
    )
  }

  n_individuals <- nrow(fam)

  if (n_individuals < 2L) {
    stop(
      "Fewer than two individuals in: ",
      fam_file
    )
  }


  # Hill-Weir / Marroni sample size:
  # number of sampled alleles

  n_alleles <- 2 * n_individuals


  list(
    n_individuals = n_individuals,
    n_alleles = n_alleles
  )
}


# =============================================================================
# INITIALIZE EXACT-DISTANCE ACCUMULATOR
# =============================================================================
#
# For each integer physical distance d:
#
#   N[d] = number of SNP pairs at distance d
#   S[d] = sum of pairwise r² values at distance d
#
# Then:
#
#   mean_r²[d] = S[d] / N[d]
#
# =============================================================================

new_accumulator <- function(max_distance_bp) {

  list(

    N = numeric(
      max_distance_bp + 1L
    ),

    S = numeric(
      max_distance_bp + 1L
    )
  )
}


# =============================================================================
# MEMORY-EFFICIENT IMPORT OF PLINK LD OUTPUT
# =============================================================================

read_ld_exact_distances <- function(
    file,
    max_distance_bp = MAX_DISTANCE_BP,
    chunk_lines = CHUNK_LINES) {


  message(
    "Reading LD file: ",
    file
  )


  accumulator <- new_accumulator(
    max_distance_bp
  )


  con <- gzfile(
    file,
    open = "rt"
  )

  on.exit(
    close(con),
    add = TRUE
  )


  # ---------------------------------------------------------------------------
  # Read header
  # ---------------------------------------------------------------------------

  header_line <- readLines(
    con,
    n = 1L,
    warn = FALSE
  )


  if (!length(header_line)) {

    stop(
      "Empty PLINK LD file: ",
      file
    )
  }


  header <- strsplit(
    trimws(header_line),
    "[[:space:]]+"
  )[[1L]]


  required_columns <- c(
    "CHR_A",
    "BP_A",
    "CHR_B",
    "BP_B",
    "R2"
  )


  column_indices <- match(
    required_columns,
    header
  )


  if (anyNA(column_indices)) {

    stop(
      "Required columns not found in ",
      file,
      ". Expected: ",
      paste(
        required_columns,
        collapse = ", "
      )
    )
  }


  # ---------------------------------------------------------------------------
  # Read file in chunks
  # ---------------------------------------------------------------------------

  repeat {

    lines <- readLines(
      con,
      n = chunk_lines,
      warn = FALSE
    )


    if (!length(lines)) {
      break
    }


    dt <- fread(
      text = paste(
        lines,
        collapse = "\n"
      ),
      header = FALSE,
      select = column_indices,
      showProgress = FALSE
    )


    setnames(
      dt,
      required_columns
    )


    # -------------------------------------------------------------------------
    # Basic quality filtering
    # -------------------------------------------------------------------------

    dt <- dt[
      !is.na(CHR_A) &
        !is.na(CHR_B) &
        !is.na(BP_A) &
        !is.na(BP_B) &
        !is.na(R2)
    ]


    if (!nrow(dt)) {
      next
    }


    # -------------------------------------------------------------------------
    # Retain only intra-chromosomal comparisons
    #
    # PLINK --r2 normally reports intra-chromosomal comparisons in this
    # workflow. This additional check explicitly ensures that no
    # inter-chromosomal pairs contribute to physical-distance calculations.
    # -------------------------------------------------------------------------

    dt <- dt[
      CHR_A == CHR_B
    ]


    if (!nrow(dt)) {
      next
    }


    # -------------------------------------------------------------------------
    # Retain valid r² observations
    # -------------------------------------------------------------------------

    dt <- dt[
      is.finite(R2) &
        R2 >= 0 &
        R2 <= 1
    ]


    if (!nrow(dt)) {
      next
    }


    # -------------------------------------------------------------------------
    # Exact physical distance
    # -------------------------------------------------------------------------

    dt[
      ,
      distance := as.integer(
        abs(BP_B - BP_A)
      )
    ]


    dt <- dt[
      distance >= 0L &
        distance <= max_distance_bp
    ]


    if (!nrow(dt)) {
      next
    }


    # -------------------------------------------------------------------------
    # Aggregate only observations having EXACTLY the same physical distance
    # -------------------------------------------------------------------------

    exact_distance <- dt[
      ,
      .(
        N = .N,
        S = sum(R2)
      ),
      by = distance
    ]


    index <- exact_distance$distance + 1L


    accumulator$N[index] <-
      accumulator$N[index] +
      exact_distance$N


    accumulator$S[index] <-
      accumulator$S[index] +
      exact_distance$S
  }


  accumulator
}


# =============================================================================
# HILL-WEIR GENOME-WIDE FIT
# =============================================================================

fit_population <- function(
    population,
    config) {


  message("")
  message(
    "========================================"
  )
  message(
    "Population: ",
    population,
    " (",
    config$species,
    ")"
  )
  message(
    "========================================"
  )


  # ---------------------------------------------------------------------------
  # Sample size
  # ---------------------------------------------------------------------------

  sample_info <- get_sample_size(
    config$fam_file
  )


  n <- sample_info$n_alleles


  message(
    "Individuals: ",
    sample_info$n_individuals
  )

  message(
    "Sampled alleles (n): ",
    n
  )


  # ---------------------------------------------------------------------------
  # Read and aggregate pairwise LD
  # ---------------------------------------------------------------------------

  accumulator <- read_ld_exact_distances(
    config$ld_file
  )


  represented <- which(
    accumulator$N > 0
  )


  if (!length(represented)) {

    stop(
      "No usable pairwise LD observations for ",
      population
    )
  }


  distance <- as.numeric(
    represented - 1L
  )


  n_pairs <- accumulator$N[
    represented
  ]


  mean_r2 <- accumulator$S[
    represented
  ] / n_pairs


  fit_data <- data.table(

    distance = distance,
    mean_r2 = mean_r2,
    n_pairs = n_pairs
  )


  setorder(
    fit_data,
    distance
  )


  message(
    "Pairwise SNP comparisons: ",
    format(
      sum(fit_data$n_pairs),
      big.mark = ",",
      scientific = FALSE
    )
  )


  message(
    "Exact physical distances represented: ",
    nrow(fit_data)
  )


  # ---------------------------------------------------------------------------
  # Weighted nonlinear least-squares Hill-Weir fitting
  #
  # Original Marroni implementation fits individual pairwise observations.
  #
  # Here, exact-distance means are fitted using the number of SNP pairs
  # contributing to each distance as weights.
  # ---------------------------------------------------------------------------

  HW_fit <- nls(

    mean_r2 ~
      ((10 + C * distance) /
         ((2 + C * distance) *
            (11 + C * distance))) *

      (1 +

         ((3 + C * distance) *
            (12 +
               12 * C * distance +
               (C * distance)^2)) /

         (n *
            (2 + C * distance) *
            (11 + C * distance))
      ),

    data = fit_data,

    start = list(
      C = 0.1
    ),

    weights = n_pairs,

    control = nls.control(
      maxiter = 200,
      warnOnly = FALSE
    )
  )


  C_estimated <- as.numeric(
    coef(HW_fit)[["C"]]
  )


  message(
    "Estimated C: ",
    format(
      C_estimated,
      scientific = TRUE
    )
  )


  # ---------------------------------------------------------------------------
  # Fitted r² values at the exact observed physical distances
  #
  # These correspond to Marroni's "fpoints".
  # ---------------------------------------------------------------------------

  fpoints <- predict(
    HW_fit,
    newdata = fit_data
  )


  fit_data[
    ,
    fitted_r2 := as.numeric(
      fpoints
    )
  ]


  # ---------------------------------------------------------------------------
  # HALF-DECAY DISTANCE
  #
  # Marroni implementation:
  #
  #   maxld = max(fpoints)
  #   h.decay = maxld / 2
  #
  # The approximate half-decay distance is the observed physical distance
  # whose fitted r² is closest to half of the maximum estimated r².
  # ---------------------------------------------------------------------------

  maximum_fitted_r2 <- max(
    fit_data$fitted_r2,
    na.rm = TRUE
  )


  half_maximum_fitted_r2 <-
    maximum_fitted_r2 / 2


  half_index <- which.min(
    abs(
      fit_data$fitted_r2 -
        half_maximum_fitted_r2
    )
  )


  half_decay_distance_bp <-
    fit_data$distance[
      half_index
    ]


  estimated_r2_at_half_decay <-
    fit_data$fitted_r2[
      half_index
    ]


  message(
    "Maximum fitted r2: ",
    round(
      maximum_fitted_r2,
      6
    )
  )


  message(
    "Half maximum fitted r2: ",
    round(
      half_maximum_fitted_r2,
      6
    )
  )


  message(
    "Half-decay distance: ",
    round(
      half_decay_distance_bp / 1000,
      3
    ),
    " kb"
  )


  # ---------------------------------------------------------------------------
  # Smooth fitted curve for graphical representation
  #
  # This does NOT alter the estimation of the half-decay distance, which
  # remains based on the fitted values at the exact observed distances,
  # following the Marroni implementation.
  # ---------------------------------------------------------------------------

  curve_distance <- seq(
    from = 0,
    to = MAX_DISTANCE_BP,
    length.out = 5000
  )


  curve_data <- data.table(

    Population = population,

    Species = config$species,

    Distance_bp = curve_distance,

    Estimated_R2 = HW_function(
      curve_distance,
      C_estimated,
      n
    )
  )


  # ---------------------------------------------------------------------------
  # Summary
  # ---------------------------------------------------------------------------

  summary_data <- data.table(

    Reference = REF_PREFIX,

    Population = population,

    Species = config$species,

    N_individuals =
      sample_info$n_individuals,

    N_alleles =
      sample_info$n_alleles,

    N_SNP_pairs =
      sum(fit_data$n_pairs),

    N_exact_distances =
      nrow(fit_data),

    C_estimated =
      C_estimated,

    Maximum_fitted_R2 =
      maximum_fitted_r2,

    Half_maximum_fitted_R2 =
      half_maximum_fitted_r2,

    Half_decay_distance_bp =
      half_decay_distance_bp,

    Half_decay_distance_kb =
      half_decay_distance_bp / 1000,

    Estimated_R2_at_half_decay =
      estimated_r2_at_half_decay
  )


  # ---------------------------------------------------------------------------
  # Return
  # ---------------------------------------------------------------------------

  list(

    summary = summary_data,

    exact_distance_data = fit_data,

    curve = curve_data,

    model = HW_fit
  )
}


